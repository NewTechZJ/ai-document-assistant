package com.demo.aidocumentassistant.chat;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Response from {@code POST /api/v1/chat}.
 */
@Schema(description = "AI model reply")
public record ChatReply(

        @Schema(description = "Text generated by the model", example = "Hello! How can I help?")
        String reply,

        @Schema(description = "Model that answered", example = "us.anthropic.claude-haiku-4-5-20251001-v1:0")
        String model,

        @Schema(description = "Input tokens used; null if the provider did not report it", example = "12")
        Integer inputTokens,

        @Schema(description = "Output tokens used; null if the provider did not report it", example = "25")
        Integer outputTokens,

        @Schema(description = "Time the model call took, in milliseconds", example = "840")
        long latencyMs
) {
}
