package com.demo.aidocumentassistant.document;

import com.demo.aidocumentassistant.common.error.NotAPdfException;
import com.demo.aidocumentassistant.common.error.ServerBusyException;
import com.demo.aidocumentassistant.ingestion.IngestionConfig;
import com.demo.aidocumentassistant.ingestion.IngestionService;
import com.demo.aidocumentassistant.ingestion.TestPdfs;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.webmvc.test.autoconfigure.WebMvcTest;
import org.springframework.context.annotation.Import;
import org.springframework.http.MediaType;
import org.springframework.mock.web.MockMultipartFile;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.ResultActions;

import java.nio.charset.StandardCharsets;
import java.time.Instant;
import java.util.List;

import static org.hamcrest.Matchers.startsWith;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.verifyNoInteractions;
import static org.mockito.Mockito.when;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.multipart;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.content;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.header;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/** Real extractor and chunker (via IngestionConfig) behind the controller; PDFs are generated by TestPdfs. */
@WebMvcTest({DocumentController.class, DocumentPreviewController.class})
@ActiveProfiles("local") // DocumentPreviewController is @Profile("local")
@Import({DocumentPreviewService.class, IngestionConfig.class})
class DocumentControllerTest {

    private static final Instant CREATED = Instant.parse("2026-11-04T12:00:00Z");

    private static final String URL = "/api/v1/documents";
    private static final String URL_PREVIEW = URL + "/preview";

    @Autowired
    MockMvc mockMvc;

    @MockitoBean
    IngestionService ingestionService;

    @MockitoBean
    DocumentRepository documentRepository;

    @Test
    void validPdfReturnsThePreview() throws Exception {
        upload("report.pdf", TestPdfs.withPages("First page.", "", "Third page."))
                .andExpect(status().isOk())
                .andExpect(content().contentTypeCompatibleWith(MediaType.APPLICATION_JSON))
                .andExpect(jsonPath("$.docId", startsWith("preview-")))
                .andExpect(jsonPath("$.fileName").value("report.pdf"))
                .andExpect(jsonPath("$.pageCount").value(3))
                .andExpect(jsonPath("$.blankPageCount").value(1))
                .andExpect(jsonPath("$.chunkCount").value(2))
                .andExpect(jsonPath("$.pages[1].chunkCount").value(0))
                .andExpect(jsonPath("$.chunks[1].pageNumber").value(3))
                .andExpect(jsonPath("$.chunks[1].text").value("Third page."))
                .andExpect(jsonPath("$.settings.targetChars").value(1800));
    }

    // ---------------------------------------------------------------- file name
    @ParameterizedTest(name = "[{index}] \"{0}\" -> {1}")
    @CsvSource(delimiter = '|', nullValues = "NULL", value = {
            "C:\\Users\\me\\a.pdf  | a.pdf",
            "/home/me/b.pdf        | b.pdf",
            "../../etc/c.pdf       | c.pdf",
            "folder/               | upload.pdf",
            "'   '                 | upload.pdf",
            "NULL                  | upload.pdf",
            "'  spaced name.pdf '  | spaced name.pdf",
    })
    void fileNameIsReducedToItsLastPathSegment(String sentName, String expected) throws Exception {
        upload(sentName, TestPdfs.withPages("x1"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.fileName").value(expected));
    }

    // ---------------------------------------------------------------- client errors
    @Test
    void emptyFileIsBadRequest() throws Exception {
        upload("a.pdf", new byte[0])
                .andExpect(status().isBadRequest())
                .andExpect(content().contentTypeCompatibleWith(MediaType.APPLICATION_PROBLEM_JSON))
                .andExpect(jsonPath("$.title").value("Bad request"))
                .andExpect(jsonPath("$.detail").value("The uploaded file is empty."))
                .andExpect(jsonPath("$.code").value("BAD_REQUEST"));
    }

    @Test
    void missingFilePartIsBadRequest() throws Exception {
        mockMvc.perform(multipart(URL_PREVIEW).file(new MockMultipartFile("document", "a.pdf", "application/pdf",
                        TestPdfs.withPages("x"))))
                .andExpect(status().isBadRequest());
    }

    @Test
    void jsonBodyIsUnsupportedMediaType() throws Exception {
        mockMvc.perform(post(URL_PREVIEW).contentType(MediaType.APPLICATION_JSON).content("{}"))
                .andExpect(status().isUnsupportedMediaType());
    }

    // ---------------------------------------------------------------- PDF errors -> ProblemDetail
    @Test
    void notAPdfIs415() throws Exception {
        expectProblem(upload("a.pdf", "hello".getBytes(StandardCharsets.US_ASCII)), 415, "Not a PDF", "NOT_A_PDF");
    }

    @Test
    void passwordProtectedPdfIs422() throws Exception {
        expectProblem(upload("a.pdf", TestPdfs.userPasswordProtected("x")), 422, "Encrypted PDF", "PDF_ENCRYPTED");
    }

    @Test
    void extractionDeniedPdfIs422() throws Exception {
        expectProblem(upload("a.pdf", TestPdfs.ownerPasswordOnly("x", false)), 422, "Encrypted PDF", "PDF_ENCRYPTED");
    }

    @Test
    void scannedPdfIs422() throws Exception {
        expectProblem(upload("a.pdf", TestPdfs.withPages("")), 422, "No extractable text", "PDF_NO_TEXT");
    }

    @Test
    void corruptPdfIs422() throws Exception {
        upload("a.pdf", "%PDF-1.7\ngarbage".getBytes(StandardCharsets.US_ASCII))
                .andExpect(status().is(422))
                .andExpect(content().contentTypeCompatibleWith(MediaType.APPLICATION_PROBLEM_JSON));
    }

    @Test
    void uploadReturns201WithDocIdAndCounts() throws Exception {
        byte[] bytes = "%PDF-fake".getBytes(StandardCharsets.US_ASCII);
        when(ingestionService.ingest(eq("report.pdf"), any(byte[].class)))
                .thenReturn(Document.processing("doc-1", "report.pdf", bytes.length, CREATED).ready(12, 30));

        mockMvc.perform(multipart(URL).file(pdf("C:\\Users\\me\\report.pdf", bytes)))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.docId").value("doc-1"))
                .andExpect(jsonPath("$.fileName").value("report.pdf"))
                .andExpect(jsonPath("$.status").value("READY"))
                .andExpect(jsonPath("$.pageCount").value(12))
                .andExpect(jsonPath("$.chunkCount").value(30));
    }

    @Test
    void emptyFileIs400() throws Exception {
        mockMvc.perform(multipart(URL).file(pdf("empty.pdf", new byte[0])))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.code").value("BAD_REQUEST"));
        verifyNoInteractions(ingestionService);
    }

    @Test
    void missingFilePartIs400() throws Exception {
        mockMvc.perform(multipart(URL))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.code").value("MISSING_PART"));
    }

    @Test
    void uploadNotAPdfIs415() throws Exception {
        when(ingestionService.ingest(anyString(), any(byte[].class))).thenThrow(new NotAPdfException("Not a PDF."));

        mockMvc.perform(multipart(URL).file(pdf("notes.txt", "hello".getBytes(StandardCharsets.UTF_8))))
                .andExpect(status().isUnsupportedMediaType())
                .andExpect(jsonPath("$.code").value("NOT_A_PDF"));
    }

    @Test
    void busyIs503WithRetryAfter() throws Exception {
        when(ingestionService.ingest(anyString(), any(byte[].class))).thenThrow(new ServerBusyException("busy"));

        mockMvc.perform(multipart(URL).file(pdf("a.pdf", "%PDF-".getBytes(StandardCharsets.US_ASCII))))
                .andExpect(status().isServiceUnavailable())
                .andExpect(header().string("Retry-After", "5"));
    }

    @Test
    void listReturnsAllDocuments() throws Exception {
        when(documentRepository.findAll()).thenReturn(List.of(
                Document.processing("doc-2", "b.pdf", 20, CREATED).failed("The PDF is password-protected."),
                Document.processing("doc-1", "a.pdf", 10, CREATED).ready(3, 5)));

        mockMvc.perform(get(URL))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.length()").value(2))
                .andExpect(jsonPath("$[0].docId").value("doc-2"))
                .andExpect(jsonPath("$[0].status").value("FAILED"))
                .andExpect(jsonPath("$[0].error").value("The PDF is password-protected."))
                .andExpect(jsonPath("$[1].chunkCount").value(5));
    }


    // ---------------------------------------------------------------- helpers
    private ResultActions upload(String fileName, byte[] bytes) throws Exception {
        return mockMvc.perform(multipart(URL_PREVIEW).file(new MockMultipartFile("file", fileName, "application/pdf", bytes)));
    }

    private static void expectProblem(ResultActions result, int status, String title, String code) throws Exception {
        result.andExpect(status().is(status))
                .andExpect(content().contentTypeCompatibleWith(MediaType.APPLICATION_PROBLEM_JSON))
                .andExpect(jsonPath("$.status").value(status))
                .andExpect(jsonPath("$.title").value(title))
                .andExpect(jsonPath("$.code").value(code))
                .andExpect(jsonPath("$.detail").isNotEmpty());
    }

    private static MockMultipartFile pdf(String name, byte[] bytes) {
        return new MockMultipartFile("file", name, "application/pdf", bytes);
    }
}
