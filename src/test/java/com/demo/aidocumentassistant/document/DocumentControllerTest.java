package com.demo.aidocumentassistant.document;

import com.demo.aidocumentassistant.ingestion.IngestionConfig;
import com.demo.aidocumentassistant.ingestion.TestPdfs;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.webmvc.test.autoconfigure.WebMvcTest;
import org.springframework.context.annotation.Import;
import org.springframework.http.MediaType;
import org.springframework.mock.web.MockMultipartFile;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.ResultActions;

import java.nio.charset.StandardCharsets;

import static org.hamcrest.Matchers.startsWith;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.multipart;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.content;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/** Real extractor and chunker (via IngestionConfig) behind the controller; PDFs are generated by TestPdfs. */
@WebMvcTest(DocumentController.class)
@Import({DocumentPreviewService.class, IngestionConfig.class})
class DocumentControllerTest {

    private static final String URL = "/api/documents/preview";

    @Autowired
    MockMvc mockMvc;

    @Test
    void validPdfReturnsThePreview() throws Exception {
        upload("report.pdf", TestPdfs.withPages("First page.", "", "Third page."))
                .andExpect(status().isOk())
                .andExpect(content().contentTypeCompatibleWith(MediaType.APPLICATION_JSON))
                .andExpect(jsonPath("$.docId", startsWith("preview-")))
                .andExpect(jsonPath("$.fileName").value("report.pdf"))
                .andExpect(jsonPath("$.pageCount").value(3))
                .andExpect(jsonPath("$.blankPageCount").value(1))
                .andExpect(jsonPath("$.chunkCount").value(2))
                .andExpect(jsonPath("$.pages[1].chunkCount").value(0))
                .andExpect(jsonPath("$.chunks[1].pageNumber").value(3))
                .andExpect(jsonPath("$.chunks[1].text").value("Third page."))
                .andExpect(jsonPath("$.settings.targetChars").value(1800));
    }

    // ---------------------------------------------------------------- file name

    @ParameterizedTest(name = "[{index}] \"{0}\" -> {1}")
    @CsvSource(delimiter = '|', nullValues = "NULL", value = {
            "C:\\Users\\me\\a.pdf  | a.pdf",
            "/home/me/b.pdf        | b.pdf",
            "../../etc/c.pdf       | c.pdf",
            "folder/               | upload.pdf",
            "'   '                 | upload.pdf",
            "NULL                  | upload.pdf",
            "'  spaced name.pdf '  | spaced name.pdf",
    })
    void fileNameIsReducedToItsLastPathSegment(String sentName, String expected) throws Exception {
        upload(sentName, TestPdfs.withPages("x1"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.fileName").value(expected));
    }

    // ---------------------------------------------------------------- client errors

    @Test
    void emptyFileIsBadRequest() throws Exception {
        upload("a.pdf", new byte[0])
                .andExpect(status().isBadRequest())
                .andExpect(content().contentTypeCompatibleWith(MediaType.APPLICATION_PROBLEM_JSON))
                .andExpect(jsonPath("$.title").value("Bad request"))
                .andExpect(jsonPath("$.detail").value("The uploaded file is empty."))
                .andExpect(jsonPath("$.code").value("BAD_REQUEST"));
    }

    @Test
    void missingFilePartIsBadRequest() throws Exception {
        mockMvc.perform(multipart(URL).file(new MockMultipartFile("document", "a.pdf", "application/pdf",
                        TestPdfs.withPages("x"))))
                .andExpect(status().isBadRequest());
    }

    @Test
    void jsonBodyIsUnsupportedMediaType() throws Exception {
        mockMvc.perform(post(URL).contentType(MediaType.APPLICATION_JSON).content("{}"))
                .andExpect(status().isUnsupportedMediaType());
    }

    // ---------------------------------------------------------------- PDF errors -> ProblemDetail

    @Test
    void notAPdfIs415() throws Exception {
        expectProblem(upload("a.pdf", "hello".getBytes(StandardCharsets.US_ASCII)), 415, "Not a PDF", "NOT_A_PDF");
    }

    @Test
    void passwordProtectedPdfIs422() throws Exception {
        expectProblem(upload("a.pdf", TestPdfs.userPasswordProtected("x")), 422, "Encrypted PDF", "PDF_ENCRYPTED");
    }

    @Test
    void extractionDeniedPdfIs422() throws Exception {
        expectProblem(upload("a.pdf", TestPdfs.ownerPasswordOnly("x", false)), 422, "Encrypted PDF", "PDF_ENCRYPTED");
    }

    @Test
    void scannedPdfIs422() throws Exception {
        expectProblem(upload("a.pdf", TestPdfs.withPages("")), 422, "No extractable text", "PDF_NO_TEXT");
    }

    @Test
    void corruptPdfIs422() throws Exception {
        upload("a.pdf", "%PDF-1.7\ngarbage".getBytes(StandardCharsets.US_ASCII))
                .andExpect(status().is(422))
                .andExpect(content().contentTypeCompatibleWith(MediaType.APPLICATION_PROBLEM_JSON));
    }

    // ---------------------------------------------------------------- helpers

    private ResultActions upload(String fileName, byte[] bytes) throws Exception {
        return mockMvc.perform(multipart(URL).file(new MockMultipartFile("file", fileName, "application/pdf", bytes)));
    }

    private static void expectProblem(ResultActions result, int status, String title, String code) throws Exception {
        result.andExpect(status().is(status))
                .andExpect(content().contentTypeCompatibleWith(MediaType.APPLICATION_PROBLEM_JSON))
                .andExpect(jsonPath("$.status").value(status))
                .andExpect(jsonPath("$.title").value(title))
                .andExpect(jsonPath("$.code").value(code))
                .andExpect(jsonPath("$.detail").isNotEmpty());
    }
}
